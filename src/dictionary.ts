/**
 * Returns a Vietnamese meaning for a given English word.
 * Searches direct match, cleaned match, singular/plural forms.
 */
export function getMeaningForWord(rawWord: string): string {
  if (!rawWord) return "";
  const cleaned = rawWord
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, "");

  if (!cleaned) return "";

  // 1. Direct match
  if (COMMON_WORD_MEANINGS[cleaned]) {
    return COMMON_WORD_MEANINGS[cleaned];
  }

  // 2. Try removing trailing 's' or 'es' (plural to singular)
  if (cleaned.endsWith("es") && COMMON_WORD_MEANINGS[cleaned.slice(0, -2)]) {
    return COMMON_WORD_MEANINGS[cleaned.slice(0, -2)];
  }
  if (cleaned.endsWith("s") && COMMON_WORD_MEANINGS[cleaned.slice(0, -1)]) {
    return COMMON_WORD_MEANINGS[cleaned.slice(0, -1)];
  }

  // 3. Try hyphen to space or space to no-space
  const noSpace = cleaned.replace(/\s+/g, "");
  if (COMMON_WORD_MEANINGS[noSpace]) {
    return COMMON_WORD_MEANINGS[noSpace];
  }

  const spaceHyphen = cleaned.replace(/-/g, " ");
  if (COMMON_WORD_MEANINGS[spaceHyphen]) {
    return COMMON_WORD_MEANINGS[spaceHyphen];
  }

  return "";
}
